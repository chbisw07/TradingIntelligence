def default_policy(trade_style: TradeStyle, *, policy_version: str = "1.0") -> BaselinePolicy:
    """Return the transparent, generic engineering baseline for one cadence."""
    if policy_version != "1.0":
        raise BaselinePolicyError(f"unsupported baseline policy version: {policy_version}")
    return BaselinePolicy(
        policy_id=f"tiaf-a2.9-{trade_style.value.casefold()}",
        policy_version=policy_version,
        trade_style=trade_style,
        component_weights=_component_weights(trade_style),
        evidence_rules=_rules(trade_style),
        direction_thresholds=DirectionThresholds(
            minimum_score=52.0,
            minimum_margin=8.0,
            conflict_score=42.0,
            component_conflict_score=35.0,
        ),
        classification_thresholds=ClassificationThresholds(
            minimum_alignment=52.0,
            minimum_opportunity_score=35.0,
            early_opportunity_score=50.0,
            top_mover_momentum=70.0,
            top_mover_participation=52.0,
            mature_extension=65.0,
            mature_room=20.0,
        ),
        penalties=PenaltyPolicy(
            extension_points=25.0,
            conflict_points=15.0,
            partial_quality_points=5.0,
            degraded_quality_points=15.0,
            unavailable_quality_points=100.0,
            aging_freshness_points=4.0,
            unknown_freshness_points=8.0,
        ),
        quality_factors=(
            QualityFactor(quality=DataQuality.GOOD, factor=1.0),
            QualityFactor(quality=DataQuality.PARTIAL, factor=0.8),
            QualityFactor(quality=DataQuality.DEGRADED, factor=0.55),
            QualityFactor(quality=DataQuality.UNAVAILABLE, factor=0.0),
        ),
        critical_freshness_sources=(Source.PRIMARY,),
        rounding_digits=6,
        metadata={
            "status": "generic_engineering_baseline_not_fitted",
            "calibration": "future_A2.10_A7_evaluation",
            "completed_bar_only": True,
        },
    )
