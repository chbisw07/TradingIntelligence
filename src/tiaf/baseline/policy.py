def _selector(
    source: Source,
    evidence_id: str,
    parameters: tuple[tuple[str, int], ...] = (),
    output_name: str | None = None,
) -> EvidenceSelector:
    return EvidenceSelector(
        source=source,
        evidence_id=evidence_id,
        parameters=parameters,
        output_name=output_name,
    )


def _rule(
    rule_id: str,
    component: Component,
    source: Source,
    evidence_id: str,
    role: Role,
    transform: Transform,
    weight: float,
    *,
    parameters: tuple[tuple[str, int], ...] = (),
    output_name: str | None = None,
    required: bool = False,
    orientation: int = 1,
    scale: float | None = None,
    center: float | None = None,
    floor: float | None = None,
    target: float | None = None,
    ceiling: float | None = None,
    post_boundary_credit: float = 0.0,
    code_threshold: float = 0.0,
    positive_code: Code | None = None,
    negative_code: Code | None = None,
) -> EvidenceRule:
    return EvidenceRule(
        rule_id=rule_id,
        component=component,
        selector=_selector(source, evidence_id, parameters, output_name),
        role=role,
        transform=transform,
        weight=weight,
        required=required,
        orientation=orientation,
        scale=scale,
        center=center,
        floor=floor,
        target=target,
        ceiling=ceiling,
        post_boundary_credit=post_boundary_credit,
        code_threshold=code_threshold,
        positive_code=positive_code,
        negative_code=negative_code,
    )


def _component_weights(style: TradeStyle) -> tuple[ComponentWeight, ...]:
    if style is TradeStyle.DAY:
        values = (
            (Component.DIRECTIONAL_STRUCTURE, 0.17, 0.10, True),
            (Component.TREND_QUALITY, 0.18, 0.12, True),
            (Component.MOMENTUM, 0.18, 0.12, True),
            (Component.RELATIVE_STRENGTH, 0.10, 0.08, False),
            (Component.PARTICIPATION, 0.14, 0.14, False),
            (Component.STRUCTURAL_READINESS, 0.10, 0.16, False),
            (Component.VOLATILITY_SUITABILITY, 0.0, 0.11, False),
            (Component.REMAINING_ROOM, 0.0, 0.09, False),
            (Component.EXTENSION_CHASE_RISK, 0.0, 0.0, False),
            (Component.MULTI_TIMEFRAME_ALIGNMENT, 0.13, 0.06, False),
            (Component.DERIVATIVES_CONTEXT, 0.0, 0.02, False),
        )
    else:
        values = (
            (Component.DIRECTIONAL_STRUCTURE, 0.20, 0.12, True),
            (Component.TREND_QUALITY, 0.24, 0.16, True),
            (Component.MOMENTUM, 0.12, 0.08, True),
            (Component.RELATIVE_STRENGTH, 0.16, 0.15, False),
            (Component.PARTICIPATION, 0.08, 0.08, False),
            (Component.STRUCTURAL_READINESS, 0.07, 0.10, False),
            (Component.VOLATILITY_SUITABILITY, 0.0, 0.10, False),
            (Component.REMAINING_ROOM, 0.0, 0.13, False),
            (Component.EXTENSION_CHASE_RISK, 0.0, 0.0, False),
            (Component.MULTI_TIMEFRAME_ALIGNMENT, 0.13, 0.06, False),
            (Component.DERIVATIVES_CONTEXT, 0.0, 0.02, False),
        )
    return tuple(
        ComponentWeight(
            component=component,
            direction_weight=direction,
            opportunity_weight=opportunity,
            required=required,
        )
        for component, direction, opportunity, required in values
    )


